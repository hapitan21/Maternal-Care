
-- Separate Patient booking requests from confirmed clinic schedules.
--
-- Patient submissions are stored in public.create_patient_appointment_request.
-- A Doctor acceptance atomically creates public.schedule and marks the request
-- accepted. A decline only changes the request status. Existing schedule rows
-- are never deleted.

begin;

create table if not exists public.create_patient_appointment_request (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  patient_id uuid,
  patient_name text,
  doctor_id uuid,
  doctor_name text,
  title text,
  category text,
  description text,
  start_time timestamptz,
  end_time timestamptz,
  status text not null default 'pending',
  updated_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid
);

alter table public.create_patient_appointment_request
  add column if not exists created_at timestamptz default now(),
  add column if not exists patient_id uuid,
  add column if not exists patient_name text,
  add column if not exists doctor_id uuid,
  add column if not exists doctor_name text,
  add column if not exists title text,
  add column if not exists category text,
  add column if not exists description text,
  add column if not exists start_time timestamptz,
  add column if not exists end_time timestamptz,
  add column if not exists status text default 'pending',
  add column if not exists updated_at timestamptz default now(),
  add column if not exists reviewed_at timestamptz,
  add column if not exists reviewed_by uuid;

-- Match schedule_id to the live public.schedule primary-key type instead of
-- assuming that every installation uses the same identifier type.
do $request_schedule_id$
declare
  v_schedule_id_type text;
begin
  if not exists (
    select 1
    from pg_catalog.pg_attribute
    where attrelid = 'public.create_patient_appointment_request'::pg_catalog.regclass
      and attname = 'schedule_id'
      and not attisdropped
  ) then
    select pg_catalog.format_type(attribute.atttypid, attribute.atttypmod)
      into v_schedule_id_type
    from pg_catalog.pg_attribute as attribute
    where attribute.attrelid = 'public.schedule'::pg_catalog.regclass
      and attribute.attname = 'id'
      and not attribute.attisdropped;

    if v_schedule_id_type is null then
      raise exception 'public.schedule.id is required before installing Patient booking requests.';
    end if;

    execute pg_catalog.format(
      'alter table public.create_patient_appointment_request add column schedule_id %s',
      v_schedule_id_type
    );
  end if;
end;
$request_schedule_id$;

-- The table visible in the existing project uses bigint ids. Existing
-- PostgreSQL IDENTITY columns already generate values and must not receive
-- an additional sequence/default. Only plain bigint ids with neither an
-- identity definition nor a default receive the compatibility sequence.
do $request_id_default$
declare
  v_next_id bigint;
  v_is_identity boolean := false;
  v_has_default boolean := false;
begin
  select
    (attribute.attidentity in ('a', 'd')),
    (attribute_default.adbin is not null)
  into
    v_is_identity,
    v_has_default
  from pg_catalog.pg_attribute as attribute
  left join pg_catalog.pg_attrdef as attribute_default
    on attribute_default.adrelid = attribute.attrelid
   and attribute_default.adnum = attribute.attnum
  where attribute.attrelid =
    'public.create_patient_appointment_request'::pg_catalog.regclass
    and attribute.attname = 'id'
    and not attribute.attisdropped;

  if not coalesce(v_is_identity, false)
     and not coalesce(v_has_default, false) then
    create sequence if not exists public.create_patient_appointment_request_id_seq;

    select coalesce(max(id), 0) + 1
      into v_next_id
    from public.create_patient_appointment_request;

    perform pg_catalog.setval(
      'public.create_patient_appointment_request_id_seq'::pg_catalog.regclass,
      greatest(v_next_id, 1),
      false
    );

    alter table public.create_patient_appointment_request
      alter column id set default
      nextval('public.create_patient_appointment_request_id_seq'::pg_catalog.regclass);

    alter sequence public.create_patient_appointment_request_id_seq
      owned by public.create_patient_appointment_request.id;
  end if;
end;
$request_id_default$;

update public.create_patient_appointment_request
