-- Preserve legacy pending request rows without deleting them. They are copied
-- to the request table and retain a schedule_id link. The new UI hides the
-- legacy schedule row until it is accepted or declined.
create or replace function pg_temp.safe_request_json(value text)
returns jsonb
language plpgsql
immutable
as $$
begin
  return coalesce(value, '{}')::jsonb;
exception
  when others then return '{}'::jsonb;
end;
$$;

insert into public.create_patient_appointment_request (
  patient_id,
  patient_name,
  doctor_id,
  doctor_name,
  title,
  category,
  description,
  start_time,
  end_time,
  status,
  schedule_id,
  created_at,
  updated_at
)
select
  schedule.patient_id,
  schedule.patient_name,
  schedule.doctor_id,
  schedule.doctor_name,
  schedule.title,
  nullif(details.value ->> 'category', ''),
  nullif(details.value ->> 'notes', ''),
  schedule.start_time,
  schedule.end_time,
  'pending',
  schedule.id,
  coalesce(schedule.created_at, now()),
  now()
from public.schedule as schedule
cross join lateral (
  select pg_temp.safe_request_json(schedule.description) as value
) as details
where (
    details.value ->> 'source' = 'patient-booking-request'
    or details.value ->> 'requestedByPatient' = 'true'
  )
  and pg_catalog.lower(pg_catalog.btrim(coalesce(details.value ->> 'requestStatus', 'pending')))
    not in ('accepted', 'declined', 'rejected')
  and pg_catalog.lower(pg_catalog.btrim(coalesce(schedule.status, 'scheduled')))
    not in ('cancel', 'cancelled', 'canceled', 'completed', 'complete', 'no_show', 'no show')
on conflict (schedule_id) where schedule_id is not null do nothing;

